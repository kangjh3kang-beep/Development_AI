# shellcheck shell=bash
# ════════════════════════════════════════════════════════════════
# assert_a1_host — **「기계가 틀렸다」와 「경로가 틀렸다」를 가른다.**
#
# 왜(실증 2026-09-12): `safe-deploy.sh` 가 `cd "$REPO" || { status "FAIL cd-repo"; exit 1; }`
#   **한 문구**로 두 사건을 같은 모양으로 냈다.
#
#   ★★사고의 경로가 이 결함의 **진짜 얼굴**이다. 통합자 세션은 개발 워크트리에서 돌려
#   ㉡(기계가 틀렸다)를 만났고, **그것을 정확히 그렇게 적었다**:
#       «그 스크립트는 158 에서 도는 것입니다»   ← 원문. 옳다.
#   그런데 그 진술이 **자동 요약을 거치며 뒤집혀**
#       «Path Resolution Error — Hardcoded $HOME/Development_AI vs My_Projects»
#   라는 라벨로 인계됐고, **세 세션이 그 뒤집힌 라벨 위에서 각자 판단했다.**
#   그 라벨대로 상수를 고쳤다면 A1 에서 배포가 **영구히** 막혔을 것이다.
#   ⇒ ***옳게 쓴 사람의 진술조차, 실패 문구가 모호하면 요약 한 단계에서 뒤집힌다.***
#     고칠 것은 사람이 아니라 **문구**다.
#
# ★경로 상수를 **어느 쪽으로도** 고치면 안 되는 이유 — 그 값은 **호스트 의존**이다(동료 4e 실측):
#     A1(프로덕션):  $HOME/Development_AI 실재 · $HOME/My_Projects/... 없음
#     개발 머신  :  정반대
#   둘 다 참이다. 어느 한쪽 리터럴로 「고치면」 **반대쪽이 영구히 막힌다.**
#
# ★**함수로 뺀 이유** — 형제가 셋이다(`safe-deploy.sh`·`rollback-web.sh`·`a1-*`).
#   블록을 복붙하면 한쪽만 고쳐지는 발산이 생긴다(이 저장소의 반복 결함).
#   ***한 곳을 고치면 전역이 따라오게 한다.***
#
# 사용: assert_a1_host "$REPO" "<상태를 적는 함수 이름 또는 빈 문자열>"
#   · `$REPO` 가 있으면              → **아무것도 하지 않는다**(정상 경로에서는 한 줄도 안 돈다)
#   · `$REPO` 가 없으면 **양쪽을 재서** 무엇이 어긋났는지 말하고 **exit 11**
#
# ★★2026-09-12 R2(독립 리뷰 MAJOR-A) — **초판은 `exit 8` 이었고, 그 코드는 이미 쓰이고 있었다.**
#   `safe-deploy.sh:93`  status "ABORT prune-진행중 — 잠시 후 재시도"; exit 8
#   **두 사건의 다음 행동이 정반대다**: 「기다렸다 재시도」 vs 「재시도해도 영원히 실패」.
#   사람은 상태 문구로 갈 수 있지만 **기계는 rc 만 본다.** 하필 권장 실행법이
#   `setsid … >/dev/null 2>&1 &`(문구를 아무도 안 보는 형태)라, rc 로 판단하는 감시기는
#   **「기다렸다 재시도」를 무한 반복**한다.
#   ⇒ ***이 PR 의 명제(한 문구가 두 사건을 덮는다)를 나는 rc 축에서 그대로 반복했다.***
#     매체가 문구에서 **종료코드**로 바뀌었을 뿐이다. 미사용 코드 **11** 로 옮긴다.
#
# ★★2026-09-12 R1(독립 리뷰 MAJOR-1) — **초판은 「부재로부터 유도」했다.**
#   초판 가드는 개발 표식(`$HOME/My_Projects/...`·`$PWD/propai-platform`)이 **없으면**
#   「그러므로 A1」로 유도했다. 그래서 **표식이 둘 다 없는 기계**에서 실측하면
#       exit=1 · "★중단 — **A1 로 보이는데** … 실제 경로/체크아웃 문제입니다"
#   가 나왔다. **A1 인지 한 번도 재지 않고 A1 이라고 말한다.**
#   ***이 PR 이 고치려던 결함(한 문구가 두 사건을 덮음)을 PR 안에서 재발시킨 것이고,***
#   더 정확히는 ***«A 의 증거가 없다» 에서 «¬A 가 참이다» 를 유도***한 것이다.
#
# ★처방 — **부재를 세지 말고 대응을 만든다**(이 규율은 세션 식별에서도 같은 날 값을 냈다):
#   이 스크립트가 **실제로 어느 체크아웃에서 실행되고 있는지**를 `BASH_SOURCE` 로 재서
#   `$REPO` 와 **비교**한다. 둘 다 관측값이므로 유도가 없다.
#     · 같다  → A1 레이아웃(정상)
#     · 다르다 → **내가 다른 체크아웃에서 돌고 있다** — 그 사실을 **양쪽 값과 함께** 말한다
# ════════════════════════════════════════════════════════════════
assert_a1_host() {
  local repo="${1:?assert_a1_host: repo 경로가 필요하다}"
  local status_fn="${2:-}"
  [ -d "$repo" ] && return 0

  # ★부재로부터 유도하지 않는다 — **내가 실행되고 있는 저장소**를 직접 잰다.
  #   이 파일은 <저장소>/propai-platform/scripts/lib/ 에 있으므로 루트는 세 단계 위다.
  local self_repo
  self_repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." 2>/dev/null && pwd -P)" || self_repo=""

  # ★★R3(독립 리뷰 MEDIUM-1) — **잰 값으로 실제로 갈라야 한다.**
  #   R2 는 `self_repo` 를 **측정해 놓고 인쇄만** 했다. 그래서 기계가 읽는 축(rc·STATUS)이
  #   서로 다른 두 사건에서 **완전히 동일**했다(실측):
  #       표식 없는 기계 → ABORT wrong-checkout(REPO 부재) · rc=11
  #       개발 워크트리  → ABORT wrong-checkout(REPO 부재) · rc=11
  #   R1 에는 이름이 **둘**이었는데 R2 에서 **하나로 합쳐졌다.**
  #   ⇒ ***이 파일의 명제가 한 층 위로 옮겨간 것이다*** — 나는 rc 축을 가르면서
  #     **상태명 축에서 뭉쳤다.** 그리고 그 근거(«권장 실행법이 `setsid … >/dev/null` 이라
  #     문구를 아무도 안 본다»)는 **내가 MAJOR-A 에서 직접 쓴 것**이다.
  #   ★갈라 두면 **도달 불가 분기가 스스로 드러난다**(그게 이 처방의 부수 효과다).
  local kind
  if [ -z "$self_repo" ]; then
    kind="unknown-checkout"      # 내가 어디서 도는지조차 못 쟀다 — 이것도 「모름」이다
  elif [ "$self_repo" != "$repo" ]; then
    kind="wrong-checkout"        # 기대한 저장소와 **다른 체크아웃**에서 돌고 있다
  else
    kind="repo-missing"          # 같은데 없다 = 진짜 체크아웃 손상(경합 외 도달 불가)
  fi
  [ -n "$status_fn" ] && "$status_fn" "ABORT ${kind}(\$REPO=${repo})"
  cat >&2 <<WRONGHOST
★중단 — \$REPO 가 없습니다. **경로 상수를 고치지 마십시오.**

  기대한 저장소(\$REPO)        : ${repo}          ← **없음**
  지금 실행 중인 저장소        : ${self_repo:-(판정 불가)}
  \$HOME                       : ${HOME}

★두 값이 다르면 **경로가 틀린 것이 아니라 기계(또는 체크아웃)가 다른 것**입니다.
  이 스크립트는 배포 서버(A1)에서 돌도록 만들어졌고, **그 상수는 호스트 의존**입니다:
      A1        : \$HOME/Development_AI            **실재**
      개발 머신 : \$HOME/My_Projects/Development_AI **실재**(A1 경로는 없음)
  **둘 다 참입니다.** 어느 한쪽 리터럴로 「고치면」 **반대쪽이 영구히 막힙니다.**

  ◎ A1 에서 실행하십시오:
      ssh -i ~/.oci.key ubuntu@<A1> 'bash \$HOME/Development_AI/propai-platform/scripts/<이 스크립트>'
    (★A1 주소는 기억에서 적지 말고 저장소에서 파생하십시오)
★판정: ${kind}
  · wrong-checkout   → **기계가 다르거나 다른 체크아웃**입니다. 상수를 고치지 마십시오.
  · unknown-checkout → 내가 어디서 도는지 못 쟀습니다(BASH_SOURCE 해석 실패).
  · repo-missing     → 두 값이 **같은데** 없습니다 = 진짜 체크아웃 손상.
    ★이 분기는 «\$REPO 가 없다」와 «self_repo == \$REPO» 를 동시에 요구하므로
      **경합(삭제와 실행이 겹침) 말고는 도달 불가**입니다 — 뜨면 그 자체가 관측입니다.
WRONGHOST
  exit 11
}
