/**
 * ★상세정보팝업 **양보 계약** (2026-08-17 — 사용자 신고 "팝업이 다른 정보에 가려진다").
 *
 * ## 왜 z 로 못 고치나 — 실측으로 확정된 제약
 *
 * 상세팝업은 Leaflet `bindPopup`(**9곳**)이라 `.leaflet-container` **안**에 산다. 그 컨테이너는
 * `globals.css` 에서 `isolation:isolate; z-index:0` 이다(라이브 실측 `isolate/0`).
 * → **컨테이너 안에서 아무리 올려도** 바깥 형제(오버레이 380~500)와의 서열은 **컨테이너의 0**
 *   으로 결정된다. 실제로 프로덕션 `.leaflet-popup-pane` 의 계산된 z 는 **1** 이다
 *   (`.leaflet-pane { z-index:1 !important }` 가 pane 서열을 통째로 평탄화한다).
 *
 * 그래서 아래 셋 중 **①은 원리적으로 불가능**하다 — 처음 세운 처방이었고 폐기했다:
 *   ① ~~popupPane 을 !important 예외로 승격~~ → 격리 안이라 바깥과의 서열이 안 바뀐다
 *   ② 컨테이너 자체를 승격 → **타일까지** 올라가 레일 위를 덮는다(부작용이 더 크다)
 *   ③ **팝업이 열리면 수동적 크롬이 양보한다** ← 채택
 *
 * ## 무엇이 양보하고 무엇이 안 하나 — 기준은 "누가 열었나"
 *
 * **양보(passive)**: 사용자가 열지 않았는데 상시 떠 있는 것. 상세를 읽는 동안 물러난다.
 * **불양보(active)**: 사용자가 직접 연 것 · 결정을 기다리는 것 · 오류 고지.
 *   양보시키면 사용자의 진행을 막거나 장애를 숨기게 된다.
 *
 * ## 사용법 (2026-08-19 갱신 — 종전 설명은 stale 했다)
 *
 * `SatongMultiMap` **루트 요소**에 `data-satong-popup-open="true"/"false"` 가 붙고,
 * 양보 대상 오버레이는 `data-satong-chrome` 을 단다. 실제 감쇄는 `globals.css` 의 규칙이 한다 —
 * **컴포넌트마다 조건부 클래스를 흩뿌리지 않는다**(그 방식이 x/y 겹침을 3회 재발시킨 원인이다).
 *
 * ### 양보는 **두 단계**다 — 이분법이 결함을 정당화했다
 *
 * 처음엔 `opacity` 와 `pointer-events` 를 한 규칙에 묶었다. 그래서 "차단이 목적인 스크림"은
 * 양보시킬 수 없었고(감쇄하면 클릭이 되살아난다), 그 스크림이 팝업을 **최대 90초**(재조회
 * 타임아웃) 덮는 것을 "목적이 그러하다"며 면제로 넘겼다 — 결함을 정당화하는 통로였다.
 * 세 번째 상태를 만들어 끊는다:
 *   · `passive`        — **완전 양보**: 흐려지고 클릭도 통과시킨다(상시 고지 리본·pill)
 *   · `passive-visual` — **시각만 양보**: 흐려지지만 **계속 차단**한다(로딩 스크림)
 *   · 면제(`exemptAttr`) — 아예 안 물러난다. 사유는 아래 `exemptReasons` 에 **열거된 것만**.
 *
 * ### 도달 범위 — 자손만이 아니라 **형제**도 덮는다
 *
 * 2026-08-18 실측: 지도를 쓰는 화면들은 지도의 **형제**로 오버레이를 얹는다(8개).
 * 자손 선택자(`A B`)로는 원리적으로 안 닿아 그 표면들이 통째로 계약 밖이었다.
 * 그래서 CSS 를 **부모 스코프**(`:has(> [트리거])`)로 올렸다 — 앞선 형제·뒤따르는 형제·
 * 자손을 한 번에 덮는다.
 * ★"앞선 형제는 지도보다 먼저 그려지니 안전"은 **CSS 스펙상 거짓**이다: DOM 순서가 페인트를
 *   정하는 것은 `z-index:auto/0` 끼리일 때뿐이고(CSS 2.1 부록 E 8단계), 이 저장소 오버레이는
 *   전부 `z-[400]`(양수)이라 9단계에서 **지도 뒤에** 그려진다. 한때 그 거짓을 주석에 적었다.
 *
 * ### ★계약의 경계 — 오버레이는 지도 루트의 **직계 형제**여야 한다
 *
 * 스코프는 **딱 한 겹**(`:has(> [트리거])`)이다. 지도를 래퍼로 한 겹 더 감싸고 그 래퍼의
 * 형제로 오버레이를 두면 **계약 밖**이 된다 — CSS 가 안 닿고, 화면은 조용히 종전 결함으로
 * 돌아간다. 새 소비처는 오버레이를 지도와 **같은 부모**에 두어야 한다.
 *
 * ★한때 `:has(> * > [트리거])` 한 겹을 더 얹었다가 **걷어냈다**(2026-08-19 R3). 이유는 그것이
 *   **컴포넌트 경계를 넘기** 때문이다: `ZoningSignalMap` 처럼 소비처 루트가 곧 지도의 부모인
 *   경우, 두 번째 단계가 **그 위 소비처 컨테이너**(예: PreCheckWorkspace 의 `<section>`)까지
 *   올라가 그 섹션 자손 전체가 감쇄 대상이 됐다(리뷰어 실측 — 같은 섹션의 **남의 크롬**이
 *   흐려짐). 오늘 실피해는 0이었지만(섹션에 다른 크롬이 없었다) 지도·크롬을 하나 더 넣는
 *   순간 발생한다. 한 겹으로 좁히는 대신 "직계 형제" 규약을 명문화했다.
 * ★잔여 위험(정직): 미래의 소비처가 지도를 감싸고 **표시 없는** 오버레이를 래퍼 형제로 두면
 *   CSS 도 락도 못 잡는다. 표시를 **달았는데 도달 못 하는** 경우는 파생 락이 잡는다.
 *
 * ★한계(정직): 이것은 **가림을 없애는 게 아니라 줄이는** 처방이다. 구조적 정답은 팝업을
 *   React 오버레이로 **포탈**해 격리 밖으로 꺼내는 것이고(그러면 SATONG_UI_Z 사다리에
 *   정식으로 편입된다), `bindPopup` 9곳 교체가 필요해 후속으로 남긴다.
 */
