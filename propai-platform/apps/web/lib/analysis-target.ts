/**
 * 분석 대상 식별 키 — "지금 화면이 어느 프로젝트·어느 땅을 보고 있는가"를 한 줄 문자열로.
 *
 * ★왜 필요한가(2026-08-03 적발한 실제 증상):
 *   프로젝트를 바꿨는데 종합분석 본문이 **이전 프로젝트의 분석 결과**를 계속 보여줬다.
 *   한 화면에 머리글은 새 프로젝트, 본문은 옛 주소가 같이 떠서 어느 쪽이 진짜인지
 *   알 수 없는 상태였다.
 *
 *   원인은 "결과를 언제 지울지"를 **주소 문자열 하나로만** 판정한 것이다.
 *     - 프로젝트에 대표 주소가 없으면(다필지 프로젝트가 그렇다) 주소가 빈 값이라
 *       "달라졌다"는 판정 자체가 성립하지 않아 옛 결과가 그대로 남는다.
 *     - 주소가 같아도 프로젝트가 다르면 다른 대상인데, 주소만 보면 같다고 본다.
 *
 *   그래서 판정 키를 **프로젝트 + 주소 복합**으로 올린다. 둘 중 하나만 바뀌어도 다른
 *   대상이고, 둘 다 비어 있어도(프로젝트 해제) 이전 키와는 다른 값이 된다.
 *
 * ★키와 화면 문구를 섞지 않는다 — 이 값은 오직 같다/다르다 판정에만 쓰고 사용자에게
 *   보여주지 않는다(2026-08-02 W4 교훈 13: 규칙이 화면 문구를 읽으면 문구를 고치는
 *   순간 규칙이 소리 없이 죽는다).
 */

/** 프로젝트·주소를 하나의 비교 키로. 표시용이 아니라 비교 전용이다. */
export function analysisTargetKey(
  projectId: string | null | undefined,
  address: string | null | undefined,
): string {
  // ★구분자 방식으로는 충돌을 **막을 수 없다**(2026-08-05 R3가 반증):
  //   구분자를 줄바꿈으로 두고 "ID에도 주소에도 들어갈 수 없다"고 적어놨었는데,
  //   주소는 `.trim()`만 하므로 **내부 개행이 남는다** —
  //     key("p1\nX", "Y")  === "p1\nX\nY"
  //     key("p1",    "X\nY") === "p1\nX\nY"   ← 서로 다른 대상이 같은 키
  //   확률은 낮지만 **주석이 갖지 않은 보장을 단언**하고 있었다. 그래서 구분자를 고르는 대신
  //   길이 정보가 함께 들어가는 직렬화를 쓴다 — 어떤 문자가 들어와도 역구성이 유일하다.
  return JSON.stringify([projectId ?? "", (address ?? "").trim()]);
}
