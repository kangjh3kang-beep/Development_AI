"""인입·부대 공사비 — **부담금이 아니라 공사비**다.

## 왜 옮겼나 (2026-08-27 · 법제처 원문 실측)

종전에는 이 넷이 `utility_stage_engine` 의 **B05~B08 「부담금」** 으로 계상됐다.
**법정 부담금이 아니다** — 원문을 대조군과 함께 확인했다:

| 항목 | 코드가 부르던 이름 | 실제 |
|---|---|---|
| 전기 | 전기인입**부담금** | 전기사업법에 `시설부담금` **0회**(대조군 `'전기'` 755회). §51 「부담금」은 **전력산업기반부담금**으로 **전기 사용자**에게 부과되는 다른 것. 실제 인입비는 한전 **전기공급약관**(사적 약관) |
| 가스 | 도시가스인입**부담금** | 도시가스사업법에 **설치비용 분담금** 개념은 **실재**(`분담금` 4회)하나 산정기준은 위임 — 실무 근거는 **도시가스 공급규정** |
| 통신 | 통신인입**부담금** | 사업자와의 **사적 계약**. ★법령 근거는 **미측정** |
| 소방 | 소방시설**부담금** | 「소방시설 설치 및 관리에 관한 법률」에 `부담금` **0회** · `분담금` **0회**(대조군 `'소방'` 887회·본문 130KB). **소방시설은 건축주가 설치**하는 것이므로 **소방설비공사비** |

★**저장소가 이미 절반은 알고 있었다** — `budget_template._CHARGES` 의 note 가
*"한전 **시설분담금**(코드 B05)"*, *"도시가스 **공급규정**(코드 B06)"* 이라 적는다.
**라벨만 「부담금」이었고 주석은 공급자 약관을 가리키고 있었다.**

## 왜 값을 지우지 않는가 (B03/B04 와 처방이 다른 이유)

B03/B04 는 **법정 부담금**인데 **법이 허용하지 않는 차원**(원/세대)의 **출처 없는 값**에
**법령 인용까지 붙여** 내보내고 있었다 — 그것은 거짓이라 걷어냈다.

여기는 다르다. **인입·소방 공사비는 실제로 발생하는 사업비**이고, **공사비의 개산(概算)은
정당한 실무**다(이 저장소도 직접공사비를 `2,400,000원/㎡` 개산으로 쓴다).
거짓이었던 것은 **금액이 아니라 분류**다 — 약관·계약 비용을 **법정부담금으로 표시**한 것.

→ **금액은 그대로 두고 분류·근거 표기를 바로잡는다. 총사업비는 불변이다.**

## ★소방(종전 B08)은 **여기에 넣지 않는다 — 이중계상이다**

종전 B08 「소방시설부담금」 `3,500원/㎡` 는 **부담금도 아니고**(법에 조문 0회),
**여기(별도 공사비)로 옮길 것도 아니다.** 저장소의 **적산 실적 데이터로 실측**했다
(`data/boq_master/electrical.json` — 실적 공내역서 1건 · GFA 238,504㎡ · **재료비만**):

    전기공사  58,176 원/㎡
    통신공사  20,017 원/㎡
    소방공사  27,223 원/㎡      ← ★코드의 3,500 원/㎡ 의 **7.8배**(재료비만, 노무·경비 제외)

즉 `3,500원/㎡` 는 **소방공사비를 나타내는 값이 될 수 없다.**
그런데 소방공사는 **실재하고 크다** — 전기+통신+소방 재료비만 **105,416원/㎡** 로
직접공사비 도급단가(`2,400,000원/㎡`)의 **4.4%** 다. 노무·경비를 더하면 10~15% 수준인데,
**이것이 도급단가 밖이라면 그 도급단가 자체가 성립하지 않는다.**

→ **소방은 이미 직접공사비(도급단가)에 포함돼 있고, B08 은 그 위에 얹힌 근거 없는 추가
  계상이었다.** 그래서 **옮기지 않고 제거**한다(총사업비 −23,002,000원 · 울산 64세대 기준).

★**한계(정직 표기)**: 실적 **n=1**(주상복합) · **재료비만** · 도급단가가 소방을 포함한다고
  **저장소가 명시한 문서는 없다**(강한 방증이지 직접 확인은 아니다).
  ★**반대로 도급단가가 소방을 제외한다면** 이 제거는 과소계상이 된다 — 그때는
  `unit_price_repository` 에 **포함 범위를 명시**하고 이 판단을 다시 재야 한다.

## ★인입은 다르다 — 적산 내역서에 **없다**

`electrical.json` 에 `'인입'` **0회**, `mechanical.json` 에 **1회**(대조군: `'간선'` 270 ·
`'스프링클러'` 92 · `'가스'` 272 — 옥내 설비는 풍부하다). 한전·도시가스사에 **내는 돈**은
도급 내역서에 나타나지 않는다. **도급 밖이므로 별도 계상이 정당하다.**

## ★미측정 (지어내지 않는다)

1. **단가 출처** — `250,000`·`180,000`·`80,000`원/세대, `3,500`원/㎡ 는 전부 대량 생성 커밋
   `2b776933` 이 유일 출처이고 인용이 **0건**이다. **개산으로 표기하되 출처는 없다고 적는다.**
2. ★**직접공사비와의 중복 여부** — 직접공사비 단가(`2,400,000원/㎡` 등)가 **소방설비·옥내
   인입을 이미 포함하는지 미측정**이다. 특히 **소방(B08)은 표준품셈상 건축공사비에 포함될
   가능성이 높다.**
   ★**분류 오류가 이 의혹을 가리고 있었다** — 「부담금」 섹션에 있으면 직접공사비와 나란히
   놓이지 않아 중복이 보이지 않는다. 옮기면 **보인다.** 그것이 이 변경의 부수 효과다.
   (중복이 **새로 생기는 것이 아니다** — 종전에도 같은 금액이 총사업비에 있었다.)
"""

from __future__ import annotations

from typing import Any

__all__ = ["UTILITY_CONNECTION_ITEMS", "calculate_utility_connection_cost"]

#: 인입·부대 공사비 개산 단가. ★**출처 없음**(대량 생성 커밋이 유일 출처) — 그 사실을
#: 각 항목의 `basis` 에 **적어서** 내보낸다. 값을 지어낸 것이 아니라 **물려받은 것**이고,
#: 물려받았다는 사실 자체가 소비처에 보여야 한다.
UTILITY_CONNECTION_ITEMS: tuple[dict[str, Any], ...] = (
    {
        "code": "U01", "name": "전기 인입공사비",
        "unit": "세대", "per_unit_won": 250_000,
        "basis": "한전 전기공급약관 시설분담금(사적 약관) — ★단가 출처 미확보(개산)",
        "legal_note": "전기사업법상 「시설부담금」 조문 없음(원문 실측). §51 부담금은 전력산업기반부담금(전기 사용자 부과)으로 별개.",
    },
    {
        "code": "U02", "name": "도시가스 인입공사비",
        "unit": "세대", "per_unit_won": 180_000,
        "basis": "도시가스 공급규정상 설치비용 분담금 — ★단가 출처 미확보(개산)",
        "legal_note": "도시가스사업법에 설치비용 분담금 개념은 실재하나 산정기준은 위임(고시·공급규정).",
    },
    {
        "code": "U03", "name": "통신 인입공사비",
        "unit": "세대", "per_unit_won": 80_000,
        "basis": "통신사업자 인입공사 계약 — ★단가 출처 미확보(개산)",
        "legal_note": "법령 근거 미측정(사적 계약으로 추정).",
    },
)


def calculate_utility_connection_cost(
    *,
    total_households: int = 0,
    total_gfa_sqm: float = 0.0,
) -> dict[str, Any]:
    """인입·부대 공사비 — 종전 B05~B08 과 **금액이 동일**하다(분류만 바뀐다).

    ★**총사업비 불변**이 이 함수의 계약이다. 종전 `utility_stage_engine` 의
      B05·B06·B07(원/세대 × 세대수) · B08(원/㎡ × 연면적)과 **같은 산식·같은 단가**를 쓴다.
      금액을 바꾸는 것은 이 변경의 목적이 아니다 — 바꾸는 것은 **무엇이라고 부르는가**다.

    Returns:
        `{'items': [...], 'total_won': int}` — 각 항목은 `basis`·`legal_note` 를 싣는다.
    """
    hh = max(0, int(total_households))
    gfa = max(0.0, float(total_gfa_sqm))
    items: list[dict[str, Any]] = []
    for spec in UTILITY_CONNECTION_ITEMS:
        qty = hh if spec["unit"] == "세대" else gfa
        amount = int(round(spec["per_unit_won"] * qty))
        items.append({
            "code": spec["code"], "name": spec["name"],
            "qty": qty, "qty_unit": spec["unit"],
            "unit_price": spec["per_unit_won"], "unit_price_unit": f"원/{spec['unit']}",
            "amount_won": amount,
            # ★개산임을 **값 옆에** 싣는다 — 소비처가 「고시값」과 구별할 수 있어야 한다.
            "confidence": "estimate",
            "basis": spec["basis"],
            "legal_note": spec["legal_note"],
        })
    return {"items": items, "total_won": sum(i["amount_won"] for i in items)}
