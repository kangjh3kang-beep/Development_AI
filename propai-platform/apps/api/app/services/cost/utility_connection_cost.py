def calculate_utility_connection_cost(
    *,
    total_households: int = 0,
    total_gfa_sqm: float = 0.0,
) -> dict[str, Any]:
    """인입·부대 공사비 — 종전 B05~B08 과 **금액이 동일**하다(분류만 바뀐다).

    ★**총사업비 불변**이 이 함수의 계약이다. 종전 `utility_stage_engine` 의
      B05·B06·B07(원/세대 × 세대수) · B08(원/㎡ × 연면적)과 **같은 산식·같은 단가**를 쓴다.
      금액을 바꾸는 것은 이 변경의 목적이 아니다 — 바꾸는 것은 **무엇이라고 부르는가**다.

    Returns:
        `{'items': [...], 'total_won': int}` — 각 항목은 `basis`·`legal_note` 를 싣는다.
    """
    hh = max(0, int(total_households))
    gfa = max(0.0, float(total_gfa_sqm))
    items: list[dict[str, Any]] = []
    for spec in UTILITY_CONNECTION_ITEMS:
        qty = hh if spec["unit"] == "세대" else gfa
        amount = int(round(spec["per_unit_won"] * qty))
        items.append({
            "code": spec["code"], "name": spec["name"],
            "qty": qty, "qty_unit": spec["unit"],
            "unit_price": spec["per_unit_won"], "unit_price_unit": f"원/{spec['unit']}",
            "amount_won": amount,
            # ★개산임을 **값 옆에** 싣는다 — 소비처가 「고시값」과 구별할 수 있어야 한다.
            "confidence": "estimate",
            "basis": spec["basis"],
            "legal_note": spec["legal_note"],
        })
    # ★소방설비 — **항목은 세우되 금액은 보류**한다(단가 미확보).
    #   `#913` 이 이것을 통째로 지웠는데 **법이 분리 도급을 명한다**(§21②) — 즉 건축 도급
    #   밖의 별도 계약이므로 **별도 계상 대상**이다. 지우면 사용자는 그 사실을 알 수 없다.
    #   금액 0 이라 총사업비는 안 움직인다 — 바뀌는 것은 **누락을 고지하는가**다.
    items.append({
        "code": FIRE_PROTECTION_ITEM["code"], "name": FIRE_PROTECTION_ITEM["name"],
        "qty": gfa, "qty_unit": FIRE_PROTECTION_ITEM["unit"],
        "unit_price": None, "unit_price_unit": None,
        "amount_won": 0,
        "confidence": "unavailable", "surveyed": False,
        "basis": FIRE_PROTECTION_ITEM["basis"],
        "legal_note": FIRE_PROTECTION_ITEM["legal_note"],
    })
    return {
        "items": items,
        "total_won": sum_priced_only(items),
        "withheld_codes": [i["code"] for i in items if i.get("confidence") == "unavailable"],
    }


def sum_priced_only(items: list[dict[str, Any]]) -> int:
    """**보류 항목을 제외한** 합계.

    ★**모듈 레벨 함수인 이유**: 인라인 제너레이터면 **직접 태울 수 없어** 이 필터가
      무잠금이 된다. 실제로 그랬다 — 보류 항목의 금액이 현재 **항상 0** 이라
      필터를 지워도 합계가 안 바뀌어 변이가 **생존**했다(2026-08-27 실증).
      여기로 빼면 **합성 입력**으로 필터 자체를 태울 수 있다.

    ★**왜 0인데도 필터가 필요한가**: 지금은 보류 = 금액 0 이지만, 부분 산정(일부만 확보)이
      생기면 보류 항목이 **0이 아닌 금액**을 가질 수 있다. 그때 섞이면
      *"산정 불가"* 가 **합계에 계상된 것**으로 읽힌다.
    """
    return sum(
        int(i.get("amount_won") or 0)
        for i in items
        if i.get("confidence") != "unavailable"
    )
