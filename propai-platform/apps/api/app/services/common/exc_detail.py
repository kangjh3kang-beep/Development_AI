"""예외를 **원인이 보이는 문자열**로 바꾸는 공용 헬퍼.

## 왜 이 파일이 생겼나 (라이브 실측 2026-08-24)

등기부 발급이 멈춰 프로덕션 상태를 조회했더니 이렇게 돌아왔다:

    {"hyphen_access": "unreachable", "hyphen_access_message": "하이픈 연결 실패: "}

**사유가 빈 문자열이다.** 코드는 `f"...: {str(e)[:80]}"` 였는데, 타임아웃 계열 예외
(`httpx.ConnectTimeout()`·`ReadTimeout()`·`asyncio.TimeoutError()`)는 인자 없이 발생해
`str(e)` 가 **빈 문자열**이 된다. 그래서 *네트워크가 막힌 것인지 · 벤더가 죽은 것인지 ·
계약/한도 문제인지* 를 **응답만으로는 판별할 수 없었다**.

## 예외 **클래스명**이 기전을 가른다

    ConnectTimeout / ConnectError → TCP 단계에서 막힘(방화벽·보안목록·경로)
    ReadTimeout                   → 연결은 됐는데 응답이 없음(상대 WAF 드롭 등)
    HTTPStatusError               → 벤더가 오류를 **응답**한 것(인증·계약·한도)

한 조각이지만 **진단의 방향을 통째로 결정한다.** 그래서 메시지가 비어도 클래스명은 남긴다.
"""

from __future__ import annotations


def exc_detail(e: BaseException, *, limit: int = 160) -> str:
    """예외 → ``"클래스명: 메시지"``. 메시지가 비면 **클래스명만** 남긴다(빈 문자열 금지).

    Args:
        e: 대상 예외.
        limit: 최대 길이(로그·응답 폭주 방지).

    Returns:
        예: ``"ConnectTimeout"`` · ``"ReadTimeout: timed out"`` · ``"ConnectError: [Errno 111] ..."``
        **절대 빈 문자열을 돌려주지 않는다** — 그것이 이 헬퍼의 존재 이유다.
    """
    name = type(e).__name__
    msg = str(e).strip()
    return (f"{name}: {msg}" if msg else name)[:limit]


# ── 발급 잔액(선불) 부족 판별 ────────────────────────────────────────────
#
# 왜 별도 함수인가 (2026-08-24 실장애):
#   사용자 신고 *"등기부 발급이 잘 되다가 갑자기 안 된다"* 의 실제 원인은
#   **하이픈 민원캐시(선불 잔액) 소진**이었다. 사용자가 충전하자 즉시 정상 복구됐다.
#   그런데 그때까지 시스템이 한 말은 `"hyphen: error"` 와
#   *"발급 PDF가 이미지 형식이면 텍스트 추출이 되지 않습니다"* 뿐이었다 —
#   **원인을 알 수 없었고, 심지어 사용자 탓으로 안내했다.**
#
#   잔액은 사용자가 **직접 해결할 수 있는** 유일한 부류다(충전하면 끝난다).
#   그것을 다른 장애와 뭉개면 복구 가능한 문제가 복구 불가처럼 보인다.
#
# ★설계 원칙 — 분류는 **부가**, 원문이 **본체**:
#   벤더 오류코드를 추측해 넣지 않는다(우리가 모르는 코드를 안다고 쓰면 새 거짓말이다).
#   한국어 신호어로만 분류하고, **분류에 실패해도 벤더 원문은 그대로 실어 보낸다**.
#   즉 이 함수가 False 를 내도 사용자가 잃는 정보는 없다.

_BALANCE_SIGNALS: tuple[str, ...] = (
    "민원캐시", "잔액", "잔고", "충전", "포인트가 부족", "포인트 부족",
    "캐시가 부족", "캐시 부족", "예치금", "요금이 부족", "한도 초과", "한도가 초과",
)


def is_balance_shortage(*parts: object) -> bool:
    """벤더 응답이 **선불 잔액 부족**을 말하는가(문자 신호 기반).

    Args:
        *parts: 벤더 메시지·코드 등 판정에 쓸 조각들(None 안전).

    ★거짓 양성을 피하려고 신호어를 좁게 둔다 — "부족" 단독처럼 흔한 말은 쓰지 않는다
      (예: "정보가 부족합니다" 를 잔액 부족으로 오분류하면 엉뚱한 충전 안내가 나간다).
    """
    hay = " ".join(str(x) for x in parts if x)
    return any(sig in hay for sig in _BALANCE_SIGNALS)


def balance_shortage_notice(provider: str, raw: str) -> str:
    """잔액 부족일 때 **사용자가 무엇을 하면 되는지**까지 담은 안내.

    ★원문(`raw`)을 반드시 함께 싣는다 — 분류가 틀렸을 때 사용자가 스스로 판단할 수 있어야 한다.
    """
    return (
        f"등기 발급 **잔액(민원캐시)이 부족**합니다 — {provider} 선불 잔액을 충전하면 "
        f"즉시 재개됩니다. 발급은 건당 과금이라 잔액이 떨어지면 이 시점부터 실패합니다. "
        f"(공급자 응답: {raw})"
    )
