"""지역·지구·구역 **이름이 겹치는 서로 다른 제도**를 갈라 주는 공용 판별자.

【왜 이 파일이 생겼나 — 2026-08-19 라이브 실측】
오산시 내삼미동(PNU 4137011000200660001)의 토지이용계획을 VWorld NED 로 실조회하니
designation 에 **`성장관리권역`** 이 실려 있었다. 이것을 국토계획법의
**성장관리계획구역**(제75조의2)으로 읽어 조례 완화(건폐율 30%)를 적용하려던 계획이 있었는데,
**두 제도는 완전히 다르다.** 법제처 원문으로 확인한 사실:

| 이름 | 근거법 | 성격 |
|---|---|---|
| **성장관리권역** | **수도권정비계획법 제6조①2·제8조** | 수도권 인구·산업 배치 **권역**. 인구집중유발시설 신설·증설 **제한**(완화 아님) |
| **성장관리계획구역** | **국토계획법 제75조의2·제75조의3** | 난개발 방지 구역. 제77조①에도 **불구하고** 건폐율 완화 가능 |

즉 `성장관리권역` 에 완화를 적용하면 **경기도 성장관리권역 전역**(오산·화성·평택 등)에
근거 없는 건폐율 +10%p 가 붙는다. 이름의 두 글자 차이(`권역` vs `계획구역`)가
**과대허용과 정직한 값을 가른다.**

【실측된 실제 오염 3건】
1. `regulation_analysis_service` 가 부분일치 `"성장관리"` 로 이 권역을
   **"도시·군계획 / 지구단위계획"** 계층에 넣고 *"지구단위계획 등 세부 도시관리계획"* 이라 설명
2. 같은 부분일치로 `has_du_plan=True` 가 되어 **국토계획법 제52조(지구단위계획)** 조문이
   수도권 권역에 부착
3. 규제법령집에서 `성장관리권역` 은 **unmatched**(근거법 링크 없음) — 정작 있어야 할
   수도권정비계획법 제8조가 안 붙는다

★그래서 판별은 **부분일치 금지**다. 이 모듈이 유일한 판별 출처(SSOT)이고, 새 소비처는
정규식·`in` 연산을 직접 쓰지 말고 여기 함수를 부른다. 한 곳을 고치면 전역이 따라온다.
"""

from __future__ import annotations

# ── 수도권정비계획법 제6조① 3권역 — 국토계획법 용도구역과 **무관**하다.
#    이름에 '성장관리'가 들어가지만 완화 근거가 아니라 행위제한 근거다(제7~9조).
METRO_REGIME_NAMES: tuple[str, ...] = (
    "과밀억제권역",
    "성장관리권역",
    "자연보전권역",
)

# ── 국토계획법 성장관리계획 계열 표기(제75조의2·제75조의3).
#    '성장관리방안'은 2021년 개정 전 명칭이라 조례 본문에 아직 남아 있다(오산시 제50조 실측).
#    ★'성장관리권역'은 여기 없다 — 있으면 이 파일의 존재 이유가 사라진다.
#    ★변이감사 메모(2026-08-19): `"성장관리계획구역"` 을 지워도 테스트가 안 죽는다 —
#      바로 아래 `"성장관리계획"` 이 그것을 **부분일치로 포함**하기 때문이다. 즉 첫 항목은
#      판별자로서는 중복이고, **정식 명칭을 맨 앞에 적어 두려는 문서 목적**으로 남긴다.
#      (설명할 수 있는 생존이라 락을 더 걸지 않는다 — 변이 점수를 부풀리지 않기 위해 명시.)
GROWTH_MGMT_PLAN_NAMES: tuple[str, ...] = (
    "성장관리계획구역",
    "성장관리계획",
    "성장관리방안",
)

# ── 세부 도시관리계획(지구단위계획 계열) — 별도 지침이 용적률·건폐율·용도를 정하는 계열.
#    ★여기에 '성장관리'를 **부분일치로** 넣으면 수도권 권역이 딸려 들어온다(실측된 결함).
DETAILED_URBAN_PLAN_NAMES: tuple[str, ...] = (
    "지구단위",
    "재정비촉진",
    "정비구역",
    "도시개발",
) + GROWTH_MGMT_PLAN_NAMES


def _norm(name: object) -> str:
    """designation 이름 정규화 — 공백 제거(‘성장관리 권역’ 같은 띄어쓰기 변형 흡수)."""
    if isinstance(name, dict):
        name = name.get("district_name") or name.get("name") or ""
    return str(name or "").replace(" ", "")


def is_metro_regime(name: object) -> bool:
    """수도권정비계획법 3권역(과밀억제·성장관리·자연보전)인가."""
    nm = _norm(name)
    return any(k in nm for k in METRO_REGIME_NAMES)


def is_growth_management_plan(name: object) -> bool:
    """국토계획법 성장관리계획구역(또는 구 성장관리방안 수립지역)인가.

    ★수도권정비계획법 `성장관리권역`은 **False** — 이 한 줄이 이 모듈의 전부다.
    """
    nm = _norm(name)
    if is_metro_regime(nm):
        return False
    return any(k in nm for k in GROWTH_MGMT_PLAN_NAMES)


def is_detailed_urban_plan(name: object) -> bool:
    """지구단위계획 등 '별도 지침이 적용되는 세부 도시관리계획' 계열인가.

    `regulation_analysis_service` 의 규제계층 분류·지구단위 조문 부착이 이 판정을 쓴다.
    수도권 3권역은 세부 도시관리계획이 아니므로 **False**.
    """
    nm = _norm(name)
    if is_metro_regime(nm):
        return False
    return any(k in nm for k in DETAILED_URBAN_PLAN_NAMES)
