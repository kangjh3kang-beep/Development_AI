"""라우트 **노출 정책** — 「프론트가 부르면 안 되는 것」을 사유와 함께 선언한다.

## 왜 이 파일이 생겼나 (2026-08-27)

`scripts/orphan_routes.py` 는 라우트를 **확정 고아 / 판정 불가 / 확정 소비** 셋으로 가른다.
그 셋에는 **「프론트가 부르면 안 되는 라우트」를 표현할 자리가 없다.**

실측(`origin/main` 77ea4b5f): 라우트 **550** · 확정 소비 **414(75.3%)** · 확정 고아 **132** ·
판정 불가 **4**. 그 132 안에 이런 것들이 섞여 있다:

    POST /api/v1/webhooks/{id}/test          ← 외부 시스템이 부른다
    POST /api/v1/admin/sales-rls/apply       ← 관리자 CLI/운영 스크립트
    GET  /api/v1/admin/sales-rls/status

**이것들은 영원히 소비되지 않는 것이 정상**이다. 그런데 분류에 자리가 없어 **영원히 「고아」로
남는다** → **도달률 100% 가 원리적으로 불가능**하다. 분모에 도달할 수 없는 것이 섞여 있기 때문이다.

## 그래서 완성도를 이렇게 재정의한다

    완성도 = (확정 소비 + 의도적 비노출) / 전체
    100%  ⇔  **미분류(=설명되지 않은 고아) = 0**

★목표는 *"고아 0"* 이 아니라 **"설명되지 않은 라우트 0"** 이다. 모든 라우트가
**소비되거나, 왜 소비되지 않는지가 적혀 있거나** 둘 중 하나가 된다.

## 규율 (오늘 두 번 검증된 패턴)

- **사유는 필수다.** dict 값이므로 사유 없는 면제는 **문법적으로 불가능**하다.
- **죽은 면제는 실패**한다 — 더 이상 없는 라우트를 면제하면 테스트가 죽는다.
  면제가 쌓이면 그 자체가 다음 사람을 속인다.
- **면제는 「미배선」의 은신처가 아니다.** 사유는 *"아직 안 붙였다"* 가 아니라
  **"붙이면 안 되는 이유"** 여야 한다. 미배선은 고아로 남겨 래칫이 줄이게 한다.
"""

from __future__ import annotations

#: 라우트 → **프론트가 부르면 안 되는 이유**.
#:
#: 키는 `orphan_routes.py` 가 내는 경로 문자열과 **정확히 같아야** 한다(메서드 무관 —
#: 같은 경로의 모든 메서드에 적용된다).
#:
#: ★여기 넣기 전에 자문하라: *"이 라우트를 화면이 부르는 것이 **잘못**인가,
#:   아니면 **아직 안 부른** 것인가?"* 후자면 넣지 마라 — 고아로 남겨야 줄어든다.
INTENTIONALLY_UNEXPOSED: dict[str, str] = {
    # ★`/api/v1/webhooks/{webhook_id}/test` 를 여기 넣었다가 **뺐다**(2026-08-27).
    #   PR #895 가 웹훅 패널을 실 API 로 배선하자 그 경로가 **확정 소비로 전환**됐고,
    #   면제로 남겨 두면 `test_no_dead_exemption` 이 **#895 착지 순간 빨개진다.**
    #   ★두 PR 이 순서에 따라 서로를 깨는 상태였고, 착지 전에 재현해서 잡았다.
    #   교훈: **면제는 "지금 고아"가 아니라 "영원히 고아여야 한다"에만 넣는다.**
    #   진행 중인 배선이 걷어갈 수 있는 것은 고아로 남겨 래칫이 줄이게 한다.
    # ── 관리자 CLI/운영 스크립트 전용(화면에 버튼이 있으면 오히려 위험) ──
    "/api/v1/admin/sales-rls/apply": (
        "RLS 정책 적용은 되돌리기가 비싼 DB 작업 — 화면 버튼으로 노출하면 오조작 위험이 크다"
    ),
    "/api/v1/admin/sales-rls/rollback": (
        "RLS 롤백도 같은 이유 — 운영자가 근거를 확인하고 CLI 로 실행한다"
    ),
}


def exempt_paths() -> frozenset[str]:
    """면제 경로 집합."""
    return frozenset(INTENTIONALLY_UNEXPOSED)


def reason_for(path: str) -> str | None:
    """면제 사유(없으면 None)."""
    return INTENTIONALLY_UNEXPOSED.get(path)
