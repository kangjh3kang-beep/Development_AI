"""PNU(19자리 필지고유번호) 판정 — **`propai-platform/apps/api/app/utils/pnu.py` 의 미러**.

## 왜 복사인가

이 서비스는 **독립 이미지**다(`Dockerfile` 의 `COPY . /app` 가 이 디렉토리만 담는다).
메인 api 의 유틸을 임포트할 수 없다. 그래서 **의도적 미러**이고,
`tests/test_pnu_mirror_contract.py` 가 **두 구현이 같은 입력에서 같은 답을 내는지** 잠근다.

★`#944` 실증: 프론트·백엔드 두 미러가 **정규식 텍스트는 같은데 의미가 달랐다**
(`\\d` 의 유니코드 포함 여부). **텍스트가 같다고 같은 판정이 아니다 — 실행이 갈랐다.**
그래서 이 미러는 **텍스트 비교가 아니라 행위 비교**로 잠근다.
"""

from __future__ import annotations

import re

# ★`\d` 가 아니라 `[0-9]` 다. 파이썬 정규식의 `\d` 는 **유니코드 십진수를 포함**해서
#   전각(`１２３…`) 19자가 통과한다. 실측(2026-09-02): 그 값이 MOLIT API 인자로 나갔다.
_PNU_RE = re.compile(r"^[0-9]{19}$")


def is_valid_pnu(pnu: str | None) -> bool:
    """**소비될 그 문자열 그대로** 판정한다 — 공백을 벗겨 주지 않는다.

    ★종전 정본이 `strip()` 후 판정하다 데였다: `' 4137…0001 '` 이 통과했는데
      소비처는 **원본을 슬라이싱**해서 `[:5]` 가 `' 4137'` 이 됐다 —
      시군구·법정동·본번·부번이 **전부 한 칸 밀린다.** 거부보다 나쁘다.
      **판정한 문자열과 소비하는 문자열이 다르면 그 판정은 아무것도 보증하지 않는다.**
    """
    return bool(pnu) and bool(_PNU_RE.match(str(pnu)))
